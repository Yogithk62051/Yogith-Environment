def get_tree_image(stage):

    if stage == "Seed":
        return "seed.png"

    elif stage == "Plant":
        return "plant.png"

    elif stage == "Sapling":
        return "sapling.png"

    elif stage == "Small Tree":
        return "small_tree.png"

    elif stage == "Large Tree":
        return "large_tree.png"

    elif stage == "Fruit Tree":
        return "fruit_tree.png"

    return "seed.png"